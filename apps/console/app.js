async function route() {
  const view = document.getElementById('view');
  const hash = (location.hash || '#/dashboard').replace(/^#\//, '');
  const [name, param] = hash.split('/');
  const key = param ? `${name}/:id` : name;
  const renderer = VIEWS[key] ?? VIEWS[name] ?? VIEWS.dashboard;

  closeDrawer();
  view.textContent = '';
  view.appendChild(el('p', { class: 'loading', text: 'loading…' }));
  setStatus(`loading ${name}…`);
  renderNav(await navCounts().catch(() => ({})));
  renderNav({}, document.getElementById('sheet-nav'));

  try {
    const content = await renderer(param ? { id: decodeURIComponent(param) } : {});
    view.textContent = '';
    for (const block of [].concat(content)) if (block) view.appendChild(block);
    setStatus(`${name} ready · ${MODE_COPY[dataMode.source]?.pill ?? ''}`);
  } catch (error) {
    view.textContent = '';
    view.appendChild(el('h1', { text: 'Could not load this view' }));
    view.appendChild(el('div', { class: 'error-box', text: error.message }));
    view.appendChild(el('p', { class: 'small muted', text: 'Start the engine with: genesis serve — then open this page again. Offline with no cache yet? The bundled snapshot will appear once you load any view with the server up once.' }));
    setStatus(`error: ${error.message}`);
  }
  window.scrollTo({ top: 0 });
}

async function navCounts() {
  const [stats, health] = await Promise.all([api('/api/stats'), api('/api/health').catch(() => null)]);
  const processing = stats.processing ?? {};
  const progressPill = document.getElementById('progress-pill');
  if (progressPill) progressPill.textContent = `${stats.state?.progress_percent ?? 0}% · ${stats.state?.current_phase ?? '—'}`;
  const eventsNode = document.getElementById('status-events');
  if (eventsNode) eventsNode.textContent = `events: ${processing.events ?? 0}`;
  const indexedNode = document.getElementById('status-indexed');
  if (indexedNode) indexedNode.textContent = `indexed: ${processing.indexed_entities ?? 0}`;
  const metaNode = document.getElementById('meta-node');
  if (metaNode && health) metaNode.textContent = `node ${health.node ?? '—'}`;
  const metaSqlite = document.getElementById('meta-sqlite');
  if (metaSqlite && health) metaSqlite.textContent = `sqlite ${health.sqlite ?? '—'}`;
  const metaDeps = document.getElementById('meta-deps');
  if (metaDeps && health) metaDeps.textContent = `${health.dependencies ?? 0} dependencies`;
  const metaOffline = document.getElementById('meta-offline');
  if (metaOffline && health) metaOffline.textContent = health.offline_capable ? 'offline ready' : 'offline unavailable';
  return {
    sessions: processing.sessions, decisions: processing.decisions, tasks: processing.tasks,
    requirements: processing.requirements, evolve: processing.lessons, knowledge: processing.indexed_entities,
    graph: processing.nodes, checkpoints: stats.state?.last_checkpoint ? 1 : 0,
  };
}

