const MODE_COPY = {
  live: { pill: 'live', cls: 'pill-online', label: 'ONLINE · live data from the API' },
  cached: { pill: 'offline · cached', cls: 'pill-cached', label: 'OFFLINE · last known data (from cache)' },
  snapshot: { pill: 'snapshot', cls: 'pill-cached', label: 'SNAPSHOT · bundled data (no server reached yet)' },
  error: { pill: 'no data', cls: 'pill-offline', label: 'NO DATA · no server, no cache, no snapshot' },
  connecting: { pill: 'connecting…', cls: 'pill-offline', label: 'connecting…' },
};

function setMode(source, detail = '') {
  if (source === 'live' && dataMode.source === 'live' && !detail) return;
  dataMode.source = source;
  dataMode.detail = detail;
  if (source === 'live' || source === 'cached') dataMode.at = new Date().toISOString();

  const copy = MODE_COPY[source] ?? MODE_COPY.error;
  const pill = connectionPill();
  if (pill) {
    pill.textContent = copy.pill;
    pill.className = `pill ${copy.cls}`;
    pill.title = `${copy.label}${dataMode.at ? ` · synced ${timeAgo(dataMode.at)}` : ''}${detail ? ` · ${detail}` : ''}`;
  }

  const banner = modeBanner();
  if (banner) {
    if (source === 'live') {
      banner.hidden = true;
    } else {
      banner.hidden = false;
      banner.dataset.mode = source;
      banner.textContent = '';
      banner.appendChild(el('span', { text: copy.label }));
      if (dataMode.at) banner.appendChild(el('span', { class: 'mono', text: `synced ${timeAgo(dataMode.at)}` }));
      if (source === 'snapshot') banner.appendChild(el('span', { class: 'mono', text: 'run `genesis serve` for live data' }));
      const retry = el('button', { text: 'Retry now', onclick: () => refreshData() });
      banner.appendChild(retry);
    }
  }
  document.body.dataset.mode = source;
}

const snapshotKeyFor = (path) => path.replace(/^\/api\//, '');

function storeLocal(path, payload) {
  try {
    const text = JSON.stringify(payload);
    if (text.length > 400_000) return; // ES: no reventar la cuota | EN: do not blow the quota
    localStorage.setItem(STORAGE_PREFIX + path, JSON.stringify({ at: new Date().toISOString(), payload }));
  } catch { /* ES: cuota llena o modo privado: se ignora | EN: full quota or private mode: ignore */ }
}

function readLocal(path) {
  try {
    const raw = localStorage.getItem(STORAGE_PREFIX + path);
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    return parsed?.payload ? { at: parsed.at, payload: parsed.payload } : null;
  } catch { return null; }
}

async function readCacheStorage(path) {
  try {
    if (!('caches' in globalThis)) return null;
    const match = await caches.match(new URL(path, location.origin).href) ?? await caches.match(path);
    if (!match || !match.ok) return null;
    const type = match.headers.get('content-type') ?? '';
    return type.includes('json') ? await match.json() : await match.text();
  } catch { return null; }
}

async function readSnapshot(path) {
  if (snapshotCache === null) {
    try {
      const response = await fetch('./snapshot.json', { cache: 'no-store' });
      snapshotCache = response.ok ? await response.json() : false;
    } catch { snapshotCache = false; }
  }
  if (!snapshotCache) return null;
  const key = snapshotKeyFor(path);
  return snapshotCache.data?.[key] ?? null;
}

/**
 * ES: puerta única de datos. Orden: red → caché del SW → localStorage → snapshot.
 * EN: the single data door. Order: network → SW cache → localStorage → snapshot.
 * PT: porta única de dados. Ordem: rede → cache do SW → localStorage → snapshot.
 *
 * @param {string} path ruta de la API, p.ej. '/api/stats'
 * @param {object} [options] opciones de fetch (solo escrituras)
 */
async function api(path, options = {}) {
  try {
    const response = await fetch(path, { headers: { 'Content-Type': 'application/json' }, ...options });
    const servedFromCache = response.headers.get('X-Genesis-Offline') === 'cached';
    if (!response.ok) {
      const detail = await response.json().catch(() => ({}));
      const error = new Error(detail?.error?.message ?? `HTTP ${response.status} on ${path}`);
      error.status = response.status;
      throw error;
    }
    const type = response.headers.get('content-type') ?? '';
    const payload = type.includes('application/json') ? await response.json() : await response.text();
    if (!options.method || options.method === 'GET') storeLocal(path, payload);
    setMode(servedFromCache ? 'cached' : 'live');
    return payload;
  } catch (error) {
    if (error.status && error.status < 500 && options.method && options.method !== 'GET') throw error;

    const fromCache = await readCacheStorage(path);
    if (fromCache !== null) { setMode('cached', `cache storage for ${path}`); return fromCache; }

    const fromLocal = readLocal(path);
    if (fromLocal) { dataMode.at = fromLocal.at; setMode('cached', `local copy for ${path}`); return fromLocal.payload; }

    const fromSnapshot = await readSnapshot(path);
    if (fromSnapshot !== null) { setMode('snapshot'); return fromSnapshot; }

    setMode('error', error.message);
    throw error;
  }
}

/** ES/EN/PT: sondeo de conexión: actualiza el modo aunque nadie navegue. */
async function probe() {
  try {
    const response = await fetch('./api/health', { cache: 'no-store' });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const servedFromCache = response.headers.get('X-Genesis-Offline') === 'cached';
    setMode(servedFromCache ? 'cached' : 'live');
    if (!servedFromCache) storeLocal('/api/health', await response.clone().json());
    return !servedFromCache;
  } catch {
    const fromCache = await readCacheStorage('/api/health');
    const fromLocal = readLocal('/api/health');
    if (fromCache !== null || fromLocal) setMode('cached');
    else setMode('error');
    return false;
  }
}

