VIEWS.graph = async () => {
  const graph = await api('/api/graph?limit=220');
  const canvas = el('canvas', { id: 'graph-canvas' });
  const detail = el('div', { class: 'card' }, [el('p', { class: 'empty', text: 'Tap a node to see its full profile (what it is, why it exists, where it is used, problems, lessons, code, sessions, sources). Pinch-free: drag to pan, wheel to zoom.' })]);

  const kindColors = {
    decision: '#c792ea', technology: '#4fd1c5', requirement: '#e3b341', task: '#7aa2f7', phase: '#ff9e64',
    lesson: '#56d364', mistake: '#f85149', reference: '#8be9fd', category: '#64748b', session: '#93a2b8', architecture: '#ffffff',
  };

  const legend = el('div', { class: 'legend' }, Object.entries(kindColors)
    .filter(([kind]) => graph.nodes.some((node) => node.kind === kind))
    .map(([kind, color]) => el('span', { style: `color:${color}`, text: kind })));

  const nodes = graph.nodes.map((node, index) => ({
    ...node,
    x: Math.cos((index / graph.nodes.length) * Math.PI * 2) * 220 + 400,
    y: Math.sin((index / graph.nodes.length) * Math.PI * 2) * 180 + 260,
    vx: 0, vy: 0,
    radius: 4 + Math.min(9, (graph.edges.filter((edge) => edge.source === node.id || edge.target === node.id).length) * 0.8),
  }));
  const byId = new Map(nodes.map((node) => [node.id, node]));
  const edges = graph.edges.map((edge) => ({ source: byId.get(edge.source), target: byId.get(edge.target), weight: edge.weight, relation: edge.relation })).filter((edge) => edge.source && edge.target);

  const context = canvas.getContext('2d');
  let transform = { x: 0, y: 0, scale: 1 };
  let hovered = null;
  let alpha = 1;
  let running = true;

  const resize = () => {
    const rect = canvas.getBoundingClientRect();
    const dpr = window.devicePixelRatio || 1;
    canvas.width = Math.max(320, rect.width * dpr);
    canvas.height = Math.max(320, rect.height * dpr);
    context.setTransform(dpr, 0, 0, dpr, 0, 0);
  };

  const tick = () => {
    if (!running) return;
    const rect = canvas.getBoundingClientRect();
    const width = rect.width;
    const height = rect.height;

    for (let i = 0; i < nodes.length; i += 1) {
      for (let j = i + 1; j < nodes.length; j += 1) {
        const a = nodes[i]; const b = nodes[j];
        let dx = b.x - a.x; let dy = b.y - a.y;
        let distance = Math.sqrt(dx * dx + dy * dy) || 0.01;
        if (distance > 420) continue;
        const force = (2600 / (distance * distance)) * alpha;
        dx /= distance; dy /= distance;
        a.vx -= dx * force; a.vy -= dy * force;
        b.vx += dx * force; b.vy += dy * force;
      }
    }
    for (const edge of edges) {
      const dx = edge.target.x - edge.source.x;
      const dy = edge.target.y - edge.source.y;
      const distance = Math.sqrt(dx * dx + dy * dy) || 0.01;
      const desired = 96 + 40 / Math.max(1, edge.weight);
      const force = ((distance - desired) / distance) * 0.035 * alpha;
      edge.source.vx += dx * force; edge.source.vy += dy * force;
      edge.target.vx -= dx * force; edge.target.vy -= dy * force;
    }
    for (const node of nodes) {
      node.vx += (width / 2 - node.x) * 0.0016 * alpha;
      node.vy += (height / 2 - node.y) * 0.0016 * alpha;
      node.vx *= 0.86; node.vy *= 0.86;
      node.x += node.vx; node.y += node.vy;
    }
    alpha = Math.max(0.02, alpha * 0.995);

    context.clearRect(0, 0, width, height);
    context.save();
    context.translate(transform.x, transform.y);
    context.scale(transform.scale, transform.scale);

    for (const edge of edges) {
      context.beginPath();
      context.moveTo(edge.source.x, edge.source.y);
      context.lineTo(edge.target.x, edge.target.y);
      context.strokeStyle = `rgba(120,150,190,${Math.min(0.42, 0.06 + edge.weight * 0.05)})`;
      context.lineWidth = Math.min(2.6, 0.4 + edge.weight * 0.35);
      context.stroke();
    }
    for (const node of nodes) {
      const isHover = node === hovered;
      context.beginPath();
      context.arc(node.x, node.y, node.radius + (isHover ? 2 : 0), 0, Math.PI * 2);
      context.fillStyle = kindColors[node.kind] ?? '#93a2b8';
      context.globalAlpha = isHover ? 1 : 0.86;
      context.fill();
      context.globalAlpha = 1;
      if (isHover || node.radius > 8.5) {
        context.fillStyle = 'rgba(230,237,246,0.92)';
        context.font = '10px ui-monospace, monospace';
        context.fillText(truncate(node.label, 34), node.x + node.radius + 4, node.y + 3);
      }
    }
    context.restore();
    requestAnimationFrame(tick);
  };

  const pick = (event) => {
    const rect = canvas.getBoundingClientRect();
    const x = (event.clientX - rect.left - transform.x) / transform.scale;
    const y = (event.clientY - rect.top - transform.y) / transform.scale;
    let best = null; let bestDistance = Infinity;
    for (const node of nodes) {
      const distance = Math.hypot(node.x - x, node.y - y);
      if (distance < node.radius + 9 && distance < bestDistance) { best = node; bestDistance = distance; }
    }
    return best;
  };

  // ES: puntero unificado = ratón + dedo. Pointer Events cubren ambos con un solo
  //     juego de listeners. EN: unified pointer = mouse + finger; Pointer Events
  //     cover both with one set of listeners. PT: ponteiro unificado.
  let pointerState = null;
  canvas.addEventListener('pointerdown', (event) => {
    canvas.setPointerCapture?.(event.pointerId);
    pointerState = { x: event.clientX, y: event.clientY, moved: 0, node: pick(event) };
    hovered = pointerState.node;
  });
  canvas.addEventListener('pointermove', (event) => {
    if (!pointerState) { hovered = pick(event); return; }
    const dx = event.clientX - pointerState.x;
    const dy = event.clientY - pointerState.y;
    pointerState.moved += Math.abs(dx) + Math.abs(dy);
    if (!pointerState.node) { transform.x += dx; transform.y += dy; }
    pointerState.x = event.clientX; pointerState.y = event.clientY;
  });
  canvas.addEventListener('pointerup', async (event) => {
    const tapped = pointerState?.node ?? null;
    const wasDrag = (pointerState?.moved ?? 0) > 8;
    pointerState = null;
    if (!tapped || wasDrag) return;
    detail.textContent = '';
    detail.appendChild(el('p', { class: 'loading', text: `loading profile of ${tapped.label}…` }));
    try {
      const profile = await api(`/api/graph/node/${encodeURIComponent(tapped.id)}`);
      detail.textContent = '';
      detail.appendChild(el('div', { class: 'card-header' }, [el('strong', { text: truncate(profile.label, 60) }), badge(profile.kind, 'blue')]));
      detail.appendChild(table(['Field', 'Value'], [
        ['What is', profile.what_is], ['Why exists', profile.why_exists], ['Where used', profile.where_used],
        ['How built', profile.how_built], ['Problems', profile.problems], ['Learned', profile.learned],
        ['Code refs', (profile.code_refs ?? []).join(', ')], ['Sessions', (profile.sessions ?? []).join(', ')],
        ['Sources', (profile.sources ?? []).join(' ')],
      ].filter(([, value]) => value && String(value).length).map(([label, value]) => [label, el('span', { class: 'small', text: truncate(value, 260) })])));
      detail.appendChild(el('h3', { text: `Relations (${profile.relations.outgoing.length + profile.relations.incoming.length})` }));
      detail.appendChild(el('ul', { class: 'list small' }, [...profile.relations.outgoing, ...profile.relations.incoming].slice(0, 18)
        .map((edge) => el('li', { text: `${edge.direction === 'out' ? '→' : '←'} ${edge.relation} · ${truncate(edge.node.label, 58)} (w${edge.weight})` }))));
    } catch (error) {
      detail.textContent = '';
      detail.appendChild(el('div', { class: 'error-box', text: error.message }));
    }
  });
  canvas.addEventListener('pointercancel', () => { pointerState = null; });
  canvas.addEventListener('wheel', (event) => {
    event.preventDefault();
    const factor = event.deltaY < 0 ? 1.12 : 0.89;
    transform.scale = Math.min(3.5, Math.max(0.25, transform.scale * factor));
  }, { passive: false });

  // ES: pellizco con dos dedos (zoom táctil). EN: two-finger pinch zoom.
  const touches = new Map();
  canvas.addEventListener('touchstart', (event) => { for (const touch of event.changedTouches) touches.set(touch.identifier, touch); }, { passive: true });
  canvas.addEventListener('touchmove', (event) => {
    if (event.touches.length !== 2) return;
    event.preventDefault();
    const [a, b] = [...event.touches];
    const distance = Math.hypot(a.clientX - b.clientX, a.clientY - b.clientY);
    if (touches.size === 2) {
      const previous = [...touches.values()];
      const previousDistance = Math.hypot(previous[0].clientX - previous[1].clientX, previous[0].clientY - previous[1].clientY);
      if (previousDistance > 0) transform.scale = Math.min(3.5, Math.max(0.25, transform.scale * (distance / previousDistance)));
    }
    touches.clear();
    for (const touch of event.touches) touches.set(touch.identifier, touch);
  }, { passive: false });
  canvas.addEventListener('touchend', (event) => { for (const touch of event.changedTouches) touches.delete(touch.identifier); }, { passive: true });

  setTimeout(() => { resize(); tick(); }, 0);
  window.addEventListener('resize', resize);
  window.addEventListener('hashchange', () => { running = false; }, { once: true });

  return [
    el('h1', { text: 'Knowledge graph' }),
    el('p', { class: 'subtitle', text: `${graph.stats?.nodes ?? 0} nodes and ${graph.stats?.edges ?? 0} relations, laid out by a force simulation written from scratch. Desktop: drag to pan, wheel to zoom. Mobile: one finger pans, two fingers pinch.` }),
    legend,
    el('div', { class: 'two-col' }, [canvas, detail]),
    el('h2', { text: 'Relations by type' }),
    el('div', { class: 'row' }, Object.entries(graph.stats?.by_relation ?? {}).map(([relation, count]) => badge(`${relation}: ${count}`, 'magenta'))),
  ];
};

