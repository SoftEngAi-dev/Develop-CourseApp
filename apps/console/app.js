function table(headers, rows) {
  const head = el('thead', {}, [el('tr', {}, headers.map((header) => el('th', { text: String(header) })))]);
  const body = el('tbody', {}, rows.map((row) => el('tr', {}, [].concat(row).map((cell) => el('td', {}, [
    typeof cell === 'string' || typeof cell === 'number' ? document.createTextNode(String(cell)) : cell,
  ])))));
  // ES: envoltorio con scroll horizontal: en móvil las tablas anchas no rompen el
  //     layout, se deslizan. EN: horizontal scroll wrapper so wide tables slide on
  //     mobile instead of breaking the layout. PT: wrapper com scroll horizontal.
  return el('div', { class: 'table-scroll' }, [el('table', {}, [head, body])]);
}

