function currentViewId() {
  return (location.hash || '#/dashboard').replace(/^#\//, '').split('/')[0] || 'dashboard';
}

function renderNav(counts = {}, target = null) {
  const list = target ?? document.getElementById('nav');
  if (!list) return;
  list.textContent = '';
  const active = currentViewId();
  for (const item of NAV) {
    if (item.group) {
      list.appendChild(el('li', { class: 'nav-group', text: item.group }));
      continue;
    }
    list.appendChild(el('li', {}, [
      el('a', { class: `nav-link ${active === item.id ? 'is-active' : ''}`, href: `#/${item.id}`, dataset: { view: item.id }, onclick: closeDrawer }, [
        el('span', { text: item.icon }),
        el('span', { text: item.label }),
        counts[item.id] !== undefined ? el('span', { class: 'count', text: String(counts[item.id]) }) : null,
      ]),
    ]));
  }
  const activeItem = NAV.find((entry) => entry.id === active);
  document.querySelectorAll('.mode').forEach((node) => {
    node.classList.toggle('is-active', node.dataset.mode === (activeItem?.mode ?? 'explore'));
  });
  document.querySelectorAll('#bottom-nav .tab').forEach((tab) => {
    tab.classList.toggle('is-active', tab.dataset.view === active);
  });
}

