/* ── Utilidades DOM / DOM helpers ─────────────────────────────────────────── */

function el(tag, props = {}, children = []) {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(props)) {
    if (value === null || value === undefined || value === false) continue;
    if (key === 'class') node.className = value;
    else if (key === 'text') node.textContent = String(value);
    else if (key === 'dataset') Object.assign(node.dataset, value);
    else if (key.startsWith('on') && typeof value === 'function') node.addEventListener(key.slice(2).toLowerCase(), value);
    else node.setAttribute(key, String(value));
  }
  for (const child of [].concat(children)) {
    if (child === null || child === undefined || child === false) continue;
    node.appendChild(typeof child === 'string' || typeof child === 'number' ? document.createTextNode(String(child)) : child);
  }
  return node;
}

const badge = (text, color = '') => el('span', { class: `badge ${color ? `badge-${color}` : ''}`, text: String(text ?? '—') });
const statusColor = (status) => ({
  completed: 'green', approved: 'green', resolved: 'green', passed: 'green',
  blocked: 'red', failed: 'red', critical: 'red',
  running: 'blue', in_progress: 'blue', planned: 'yellow', stub: 'yellow', proposed: 'yellow', open: 'yellow',
}[status] ?? '');
const num = (value) => (value === null || value === undefined ? '—' : Number(value).toLocaleString('en-US'));
const truncate = (text, max = 180) => (String(text ?? '').length > max ? `${String(text).slice(0, max)}…` : String(text ?? ''));
const timeAgo = (iso) => {
  if (!iso) return 'never';
  const seconds = Math.max(0, Math.round((Date.now() - new Date(iso).getTime()) / 1000));
  if (seconds < 60) return `${seconds}s ago`;
  if (seconds < 3600) return `${Math.round(seconds / 60)}m ago`;
  if (seconds < 86400) return `${Math.round(seconds / 3600)}h ago`;
  return `${Math.round(seconds / 86400)}d ago`;
};

function highlight(snippet) {
  const text = String(snippet ?? '').replace(/\[\[/g, '\u0001').replace(/\]\]/g, '\u0002');
  const node = document.createElement('span');
  for (const part of text.split('\u0001')) {
    const [plain, marked] = part.split('\u0002');
    if (plain) node.appendChild(document.createTextNode(plain));
    if (marked) node.appendChild(el('span', { class: 'mark', text: marked }));
  }
  return node;
}

