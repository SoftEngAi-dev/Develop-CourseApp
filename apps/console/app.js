async function registerServiceWorker() {
  if (!('serviceWorker' in navigator)) {
    setMode(dataMode.source === 'connecting' ? 'error' : dataMode.source, 'no service worker support');
    return;
  }
  const secure = location.protocol === 'https:' || ['localhost', '127.0.0.1'].includes(location.hostname);
  if (!secure) return; // ES: los SW exigen HTTPS o localhost | EN: SWs require HTTPS or localhost
  try {
    swRegistration = await navigator.serviceWorker.register('./sw.js', { scope: './' });
    navigator.serviceWorker.addEventListener('message', (event) => {
      const { type, shell_entries: shellEntries, api_entries: apiEntries, version } = event.data ?? {};
      if (type === 'CACHE_STATUS') {
        const meta = document.getElementById('meta-cache');
        if (meta) meta.textContent = `sw ${version} · ${shellEntries}+${apiEntries} cached`;
      }
    });
    swRegistration.addEventListener('updatefound', () => {
      const worker = swRegistration.installing;
      worker?.addEventListener('statechange', () => {
        if (worker.state === 'installed' && navigator.serviceWorker.controller) {
          setStatus('app updated — reload to apply');
        }
      });
    });
    setTimeout(() => navigator.serviceWorker.controller?.postMessage({ type: 'CACHE_STATUS' }), 1200);
  } catch (error) {
    // ES: sin SW la app sigue funcionando (localStorage + snapshot). Sin SW la
    //     app sigue funcionando. The app still works without the SW.
    setStatus(`sw unavailable: ${error.message}`);
  }
}

